#!/usr/bin/env python3
"""Record and verify SHA-256 digests of guest/ and firmware/ source trees.

Mirrors reims-vgpu/guest/tools/prebuilt.py source-tracking discipline so staged
InfernoVgpu.fw packages remain tied to exact wire headers and guest sources.
"""

import hashlib
from pathlib import Path
import sys

GUEST_ROOT = Path(__file__).resolve().parent.parent
REPO_ROOT = GUEST_ROOT.parent

TRACKED_GLOBS = [
    "crates/inferno-vgpu-graphics/include/inferno_graphics_wire.h",
    "firmware/include/inferno_firmware_abi.h",
    "firmware/dt-overlay.plist",
    "firmware/set.toml",
    "guest/bundle/Info.plist",
    "guest/bundle/src/InfernoWireClient.hpp",
    "guest/bundle/src/InfernoWireClient.cpp",
    "guest/bundle/src/InfernoMetal.h",
    "guest/bundle/src/InfernoMetal.mm",
    "guest/driver/Info.plist",
    "guest/driver/src/InfernoVgpuDriver.hpp",
    "guest/driver/src/InfernoVgpuDriver.cpp",
]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def build_record() -> str:
    lines = ["# Auto-generated by guest/tools/bundle_manifest.py", "[sources]"]
    for rel in TRACKED_GLOBS:
        p = REPO_ROOT / rel
        if not p.is_file():
            raise SystemExit(f"bundle_manifest: missing tracked file {rel}")
        lines.append(f'"{rel}" = "{sha256_file(p)}"')
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 3 or sys.argv[1] not in ("record", "check"):
        print("Usage: bundle_manifest.py <record|check> <sources.toml>", file=sys.stderr)
        return 2
    cmd, out_path = sys.argv[1], Path(sys.argv[2])
    expected = build_record()
    if cmd == "record":
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(expected, encoding="utf-8")
        print(f"[bundle_manifest] recorded {len(TRACKED_GLOBS)} files -> {out_path}")
        return 0
    if not out_path.is_file():
        print(f"[bundle_manifest] missing {out_path}", file=sys.stderr)
        return 1
    actual = out_path.read_text(encoding="utf-8")
    if actual != expected:
        print(f"[bundle_manifest] STALE: {out_path} does not match current sources", file=sys.stderr)
        return 1
    print(f"[bundle_manifest] OK ({len(TRACKED_GLOBS)} files verified)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
